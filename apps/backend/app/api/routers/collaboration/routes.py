"""Per-entity nested notes + attachments routes.

Each entity (appointment, task, patient) exposes the same notes/attachments
surface, guarded by THAT entity's access dependency, then delegating to the
shared (authz-free) collaboration services. The route resolves
`(owner_type, owner_id, patient_id)` from the owner and passes it down.

Appointment and task share an identical surface and are generated by
`_build_owner_collab_router`; only their access dependency, owner type, path
prefix, and owner→id/patient resolvers differ. Patient routes are special and
stay explicit: GET aggregates ALL items about the patient across owners; POST
creates a `patient`-owned item.
"""

from __future__ import annotations

from collections.abc import Callable
from typing import Annotated, Any
from uuid import UUID

from fastapi import APIRouter, Depends, status

from app.core.enums.collaboration import OwnerType
from app.core.enums.user import Role
from app.db.models.task import Task
from app.schemas.auth.auth import SessionUser
from app.schemas.collaboration.attachment import (
    AttachmentCreate,
    AttachmentDownload,
    AttachmentRead,
    AttachmentUploadResponse,
)
from app.schemas.collaboration.note import NoteCreate, NoteRead
from app.services.access.identity.deps import require_role
from app.services.appointment.deps import require_appointment_access
from app.services.collaboration.deps import AttachmentServiceDep, NoteServiceDep
from app.services.patient.deps import PatientAccessDep
from app.services.task.deps import require_task_access

_GUARD = Depends(require_role(Role.ADMIN, Role.CAREGIVER))


def _build_owner_collab_router(
    *,
    prefix: str,
    id_param: str,
    singular: str,
    tag: str,
    owner_type: OwnerType,
    access: Callable[..., Any],
    get_owner_id: Callable[[Any], UUID],
    get_patient_id: Callable[[Any], UUID | None],
) -> APIRouter:
    """Build the 6-route notes/attachments surface for one owner entity.

    `access` is the owner's access dependency callable (it reads `{id_param}`
    from the path and 404s on a miss). `get_owner_id` / `get_patient_id` project
    the resolved owner; only writes need the patient, so reads never call
    `get_patient_id` (a patient-less task can still list its notes).
    """
    router = APIRouter(tags=[tag])
    owner_dep = Annotated[Any, Depends(access)]
    guard = Annotated[SessionUser, _GUARD]
    base = f"/{prefix}/{{{id_param}}}"

    async def list_notes(owner, service, current_user):  # type: ignore[no-untyped-def]
        return await service.list_for_owner(
            tenant_id=current_user.tenant_id, owner_type=owner_type, owner_id=get_owner_id(owner)
        )

    list_notes.__annotations__ = {
        "owner": owner_dep,
        "service": NoteServiceDep,
        "current_user": guard,
        "return": list[NoteRead],
    }
    list_notes.__name__ = f"list_{singular}_notes"
    router.add_api_route(f"{base}/notes", list_notes, methods=["GET"], response_model=list[NoteRead])

    async def add_note(owner, payload, service, current_user):  # type: ignore[no-untyped-def]
        return await service.add(
            owner_type=owner_type,
            owner_id=get_owner_id(owner),
            patient_id=get_patient_id(owner),
            author=current_user,
            body=payload.body,
        )

    add_note.__annotations__ = {
        "owner": owner_dep,
        "payload": NoteCreate,
        "service": NoteServiceDep,
        "current_user": guard,
        "return": NoteRead,
    }
    add_note.__name__ = f"add_{singular}_note"
    router.add_api_route(
        f"{base}/notes",
        add_note,
        methods=["POST"],
        response_model=NoteRead,
        status_code=status.HTTP_201_CREATED,
    )

    async def list_attachments(owner, service, current_user):  # type: ignore[no-untyped-def]
        return await service.list_for_owner(
            tenant_id=current_user.tenant_id, owner_type=owner_type, owner_id=get_owner_id(owner)
        )

    list_attachments.__annotations__ = {
        "owner": owner_dep,
        "service": AttachmentServiceDep,
        "current_user": guard,
        "return": list[AttachmentRead],
    }
    list_attachments.__name__ = f"list_{singular}_attachments"
    router.add_api_route(
        f"{base}/attachments",
        list_attachments,
        methods=["GET"],
        response_model=list[AttachmentRead],
    )

    async def create_attachment(owner, payload, service, current_user):  # type: ignore[no-untyped-def]
        return await service.create(
            owner_type=owner_type,
            owner_id=get_owner_id(owner),
            patient_id=get_patient_id(owner),
            uploader=current_user,
            filename=payload.filename,
            content_type=payload.content_type,
            size=payload.size,
        )

    create_attachment.__annotations__ = {
        "owner": owner_dep,
        "payload": AttachmentCreate,
        "service": AttachmentServiceDep,
        "current_user": guard,
        "return": AttachmentUploadResponse,
    }
    create_attachment.__name__ = f"create_{singular}_attachment"
    router.add_api_route(
        f"{base}/attachments",
        create_attachment,
        methods=["POST"],
        response_model=AttachmentUploadResponse,
        status_code=status.HTTP_201_CREATED,
    )

    async def attachment_url(owner, attachment_id, service, current_user):  # type: ignore[no-untyped-def]
        return await service.download_url(
            owner_type=owner_type,
            owner_id=get_owner_id(owner),
            attachment_id=attachment_id,
            tenant_id=current_user.tenant_id,
        )

    attachment_url.__annotations__ = {
        "owner": owner_dep,
        "attachment_id": UUID,
        "service": AttachmentServiceDep,
        "current_user": guard,
        "return": AttachmentDownload,
    }
    attachment_url.__name__ = f"{singular}_attachment_url"
    router.add_api_route(
        f"{base}/attachments/{{attachment_id}}/url",
        attachment_url,
        methods=["GET"],
        response_model=AttachmentDownload,
    )

    async def delete_attachment(owner, attachment_id, service, current_user):  # type: ignore[no-untyped-def]
        await service.delete(
            owner_type=owner_type,
            owner_id=get_owner_id(owner),
            attachment_id=attachment_id,
            tenant_id=current_user.tenant_id,
            caller_id=current_user.id,
        )

    delete_attachment.__annotations__ = {
        "owner": owner_dep,
        "attachment_id": UUID,
        "service": AttachmentServiceDep,
        "current_user": guard,
        "return": None,
    }
    delete_attachment.__name__ = f"delete_{singular}_attachment"
    router.add_api_route(
        f"{base}/attachments/{{attachment_id}}",
        delete_attachment,
        methods=["DELETE"],
        status_code=status.HTTP_204_NO_CONTENT,
    )

    return router


def _task_patient_id(task: Task) -> UUID | None:
    # A task need not be linked to a patient; its notes/documents simply carry
    # no patient_id and won't surface in any patient aggregate.
    return task.patient_id


appointment_collab_router = _build_owner_collab_router(
    prefix="appointments",
    id_param="appointment_id",
    singular="appointment",
    tag="appointments",
    owner_type=OwnerType.APPOINTMENT,
    access=require_appointment_access,
    get_owner_id=lambda appointment: appointment.id,
    get_patient_id=lambda appointment: appointment.patient.id,
)

task_collab_router = _build_owner_collab_router(
    prefix="tasks",
    id_param="task_id",
    singular="task",
    tag="tasks",
    owner_type=OwnerType.TASK,
    access=require_task_access,
    get_owner_id=lambda task: task.id,
    get_patient_id=_task_patient_id,
)


# ── patient (GET = aggregate across owners; POST = patient-owned) ──────────

patient_collab_router = APIRouter(tags=["patients"])


@patient_collab_router.get("/patients/{patient_id}/notes", response_model=list[NoteRead])
async def list_patient_notes(
    patient: PatientAccessDep,
    service: NoteServiceDep,
) -> list[NoteRead]:
    return await service.list_for_patient(tenant_id=patient.tenant_id, patient_id=patient.id)


@patient_collab_router.post(
    "/patients/{patient_id}/notes", response_model=NoteRead, status_code=status.HTTP_201_CREATED
)
async def add_patient_note(
    patient: PatientAccessDep,
    payload: NoteCreate,
    service: NoteServiceDep,
    current_user: Annotated[SessionUser, _GUARD],
) -> NoteRead:
    return await service.add(
        owner_type=OwnerType.PATIENT,
        owner_id=patient.id,
        patient_id=patient.id,
        author=current_user,
        body=payload.body,
    )


@patient_collab_router.get(
    "/patients/{patient_id}/attachments", response_model=list[AttachmentRead]
)
async def list_patient_attachments(
    patient: PatientAccessDep,
    service: AttachmentServiceDep,
) -> list[AttachmentRead]:
    return await service.list_for_patient(tenant_id=patient.tenant_id, patient_id=patient.id)


@patient_collab_router.post(
    "/patients/{patient_id}/attachments",
    response_model=AttachmentUploadResponse,
    status_code=status.HTTP_201_CREATED,
)
async def create_patient_attachment(
    patient: PatientAccessDep,
    payload: AttachmentCreate,
    service: AttachmentServiceDep,
    current_user: Annotated[SessionUser, _GUARD],
) -> AttachmentUploadResponse:
    return await service.create(
        owner_type=OwnerType.PATIENT,
        owner_id=patient.id,
        patient_id=patient.id,
        uploader=current_user,
        filename=payload.filename,
        content_type=payload.content_type,
        size=payload.size,
    )


@patient_collab_router.get(
    "/patients/{patient_id}/attachments/{attachment_id}/url", response_model=AttachmentDownload
)
async def patient_attachment_url(
    patient: PatientAccessDep,
    attachment_id: UUID,
    service: AttachmentServiceDep,
) -> AttachmentDownload:
    return await service.download_url(
        owner_type=OwnerType.PATIENT,
        owner_id=patient.id,
        attachment_id=attachment_id,
        tenant_id=patient.tenant_id,
    )


@patient_collab_router.delete(
    "/patients/{patient_id}/attachments/{attachment_id}", status_code=status.HTTP_204_NO_CONTENT
)
async def delete_patient_attachment(
    patient: PatientAccessDep,
    attachment_id: UUID,
    service: AttachmentServiceDep,
    current_user: Annotated[SessionUser, _GUARD],
) -> None:
    await service.delete(
        owner_type=OwnerType.PATIENT,
        owner_id=patient.id,
        attachment_id=attachment_id,
        tenant_id=current_user.tenant_id,
        caller_id=current_user.id,
    )
